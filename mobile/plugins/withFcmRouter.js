/**
 * Android only: one Firebase Messaging service for BOTH push senders.
 *
 * Why: expo-notifications (message pushes, sent by the worker through Expo) and
 * the Twilio Voice SDK (incoming calls) each declare a FirebaseMessagingService.
 * Android hands every FCM message to just one of them. Twilio's wins (Expo's is
 * declared at priority -1) and it drops anything that isn't a Twilio call, so
 * WhatsApp message notifications would never show on Android.
 *
 * Fix (Twilio's documented "out-of-band Firebase Messaging Service" approach):
 *   1. switch Twilio's own service off (its `..._firebasemessagingservice_enabled` bool)
 *   2. add MsFirebaseMessagingService, which extends Expo's service and hands
 *      Twilio call payloads to the Twilio SDK, everything else to Expo.
 *
 * NOT YET COMPILED OR RUN: written against expo-notifications 57.0.24 and
 * @twilio/voice-react-native-sdk 1.8.1 source. Check on a real Android phone
 * that both a WhatsApp push and an incoming call arrive (see README).
 */
const { withAndroidManifest, withAppBuildGradle, withDangerousMod, AndroidConfig } = require("expo/config-plugins");
const fs = require("fs");
const path = require("path");

const CLASS = "MsFirebaseMessagingService";

function kotlinSource(pkg) {
  return `package ${pkg}

import android.os.PowerManager
import com.google.firebase.messaging.RemoteMessage
import com.twilio.voice.Voice
import com.twiliovoicereactnative.CallMessageListenerProxy
import com.twiliovoicereactnative.VoiceFirebaseMessagingService
import expo.modules.notifications.service.ExpoFirebaseMessagingService

/** Generated by plugins/withFcmRouter.js. Twilio call pushes go to Twilio, the rest to Expo. */
class ${CLASS} : ExpoFirebaseMessagingService() {
  override fun onMessageReceived(remoteMessage: RemoteMessage) {
    val data = remoteMessage.data
    if (data.isNotEmpty() && data.keys.any { it.startsWith("twi_") }) {
      // Same as Twilio's own service: wake the screen so the call UI shows.
      val pm = getSystemService(POWER_SERVICE) as PowerManager
      if (!pm.isInteractive) {
        @Suppress("DEPRECATION")
        pm.newWakeLock(
          PowerManager.SCREEN_DIM_WAKE_LOCK or PowerManager.ACQUIRE_CAUSES_WAKEUP,
          "MsFirebaseMessagingService:call"
        ).acquire(30_000)
      }
      val handled = Voice.handleMessage(
        this,
        data,
        VoiceFirebaseMessagingService.MessageHandler(),
        CallMessageListenerProxy()
      )
      if (handled) return
    }
    super.onMessageReceived(remoteMessage)
  }
}
`;
}

const BOOL_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withFcmRouter.js: MsFirebaseMessagingService routes Twilio pushes instead. -->
<resources>
  <bool name="twiliovoicereactnative_firebasemessagingservice_enabled">false</bool>
</resources>
`;

function withRouterService(config) {
  return withAndroidManifest(config, (cfg) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    const pkg = cfg.android && cfg.android.package;
    if (!pkg) throw new Error("withFcmRouter: android.package is required");
    const name = `${pkg}.${CLASS}`;
    app.service = (app.service || []).filter((s) => s.$["android:name"] !== name);
    app.service.push({
      $: { "android:name": name, "android:exported": "false" },
      "intent-filter": [
        {
          $: { "android:priority": "10" },
          action: [{ $: { "android:name": "com.google.firebase.MESSAGING_EVENT" } }],
        },
      ],
    });
    return cfg;
  });
}

function withRouterFiles(config) {
  return withDangerousMod(config, [
    "android",
    async (cfg) => {
      const pkg = cfg.android && cfg.android.package;
      if (!pkg) throw new Error("withFcmRouter: android.package is required");
      const root = cfg.modRequest.platformProjectRoot;
      const javaDir = path.join(root, "app", "src", "main", "java", ...pkg.split("."));
      fs.mkdirSync(javaDir, { recursive: true });
      fs.writeFileSync(path.join(javaDir, `${CLASS}.kt`), kotlinSource(pkg));
      const valuesDir = path.join(root, "app", "src", "main", "res", "values");
      fs.mkdirSync(valuesDir, { recursive: true });
      fs.writeFileSync(path.join(valuesDir, "ms_fcm_router.xml"), BOOL_XML);
      return cfg;
    },
  ]);
}

/**
 * The Twilio and Expo modules declare their Android libraries as `implementation`,
 * so the app module can't see com.twilio.voice.Voice or RemoteMessage unless it
 * depends on them too. Versions are read from the installed Twilio module so
 * they stay in step with it.
 */
function twilioAndroidVersions() {
  const gradle = fs.readFileSync(
    path.join(path.dirname(require.resolve("@twilio/voice-react-native-sdk/package.json")), "android", "build.gradle"),
    "utf8",
  );
  const pick = (key) => {
    const m = gradle.match(new RegExp(`'${key}'\\s*:\\s*'([^']+)'`));
    if (!m) throw new Error(`withFcmRouter: couldn't read ${key} from the Twilio module's build.gradle`);
    return m[1];
  };
  return { voice: pick("voiceAndroid"), firebaseMessaging: pick("firebaseMessaging") };
}

function withRouterDependencies(config) {
  return withAppBuildGradle(config, (cfg) => {
    const marker = "// @generated withFcmRouter";
    if (cfg.modResults.contents.includes(marker)) return cfg;
    const v = twilioAndroidVersions();
    cfg.modResults.contents = cfg.modResults.contents.replace(
      /dependencies\s*\{/,
      (m) =>
        `${m}\n    ${marker}\n    implementation "com.twilio:voice-android:${v.voice}"\n    implementation "com.google.firebase:firebase-messaging:${v.firebaseMessaging}"`,
    );
    return cfg;
  });
}

module.exports = function withFcmRouter(config) {
  return withRouterDependencies(withRouterFiles(withRouterService(config)));
};
